function buildLawModal(){
  if(document.getElementById('lawMask'))return;
  var m=document.createElement('div');
  m.className='lawmask'; m.id='lawMask';
  m.innerHTML='<div class="lawbox" role="dialog" aria-modal="true"><header><span id="lawTitle"></span><span class="x" title="关闭" onclick="closeLaw()">×</span></header><div class="body" id="lawBody"></div></div>';
  m.addEventListener('click',function(e){ if(e.target===m) closeLaw(); });
  document.body.appendChild(m);
  document.addEventListener('keydown',function(e){ if(e.key==='Escape') closeLaw(); });
}
function openLaw(key){
  var d=LAW[key]; if(!d)return;
  buildLawModal();
  document.getElementById('lawTitle').textContent=d.title;
  var body=document.getElementById('lawBody');
  body.textContent=d.text;
  if(d.src){ var s=document.createElement('div'); s.className='src'; s.textContent=d.src; body.appendChild(s); }
  document.getElementById('lawMask').classList.add('show');
}
function closeLaw(){ var m=document.getElementById('lawMask'); if(m) m.classList.remove('show'); }

function bindLaw(){
  var list=Object.keys(LAW).map(function(k){return {key:k,d:LAW[k]};});
  function findLaw(t){
    var hit=list.find(function(o){ return o.d.tokens.every(function(tok){ return t.indexOf(tok)>-1; }); });
    if(hit) return hit;
    var m=t.match(/第[0-9一二三四五六七八九十百零〇\/]+条/);
    if(m){
      var num=m[0];
      hit=list.find(function(o){
        return o.d.tokens.some(function(tok){ return tok===num || num.indexOf(tok)===0; });
      });
    }
    return hit||null;
  }
  document.querySelectorAll('.law').forEach(function(el){
    var t=el.textContent;
    var hit=findLaw(t);
    if(hit){
      el.classList.add('clickable');
      el.setAttribute('role','button');
      el.setAttribute('tabindex','0');
      el.setAttribute('title','点击查看法条原文');
      el.addEventListener('click',function(){ openLaw(hit.key); });
      el.addEventListener('keydown',function(e){ if(e.key==='Enter'||e.key===' '){ e.preventDefault(); openLaw(hit.key); } });
    }
  });
}
if(document.readyState!=='loading') bindLaw();
else document.addEventListener('DOMContentLoaded', bindLaw);
